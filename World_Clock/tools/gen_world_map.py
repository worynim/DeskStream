def to_px(lon, lat):
    return ((lon + 180) * W / 360.0, (90 - lat) * H / 180.0)


def main():
    img = Image.new("1", (W, H), 0)
    d = ImageDraw.Draw(img)
    for poly in LAND.values():
        d.polygon([to_px(lo, la) for lo, la in poly], fill=1)
    px = img.load()
    rows = []
    for y in range(H):                      # XBM: 행 우선, 바이트 안에서 LSB가 왼쪽
        row = []
        for bx in range(W // 8):
            b = 0
            for bit in range(8):
                if px[bx * 8 + bit, y]:
                    b |= 1 << bit
            row.append("0x%02x" % b)
        rows.append("    " + ", ".join(row) + ",")
    with open("world_map.h", "w", encoding="utf-8") as f:
        f.write("// worynim@gmail.com\n/**\n * @file world_map.h\n"
                " * @brief 128x64 등장방형 세계 지도 비트맵 (XBM, 켜진 점 = 육지)\n"
                " * @details tools/gen_world_map.py 가 만든 파일 — 직접 고치지 않는다.\n"
                " *          x = (경도 + 180) * 128 / 360, y = (90 - 위도) * 64 / 180.\n */\n"
                "#ifndef WORLD_MAP_H\n#define WORLD_MAP_H\n\n#include <stdint.h>\n\n"
                "#ifndef U8X8_PROGMEM\n#define U8X8_PROGMEM\n#endif\n\n"
                "static const uint8_t kWorldMapBits[128 * 64 / 8] U8X8_PROGMEM = {\n")
        f.write("\n".join(rows))
        f.write("\n};\n\n#endif\n")


if __name__ == "__main__":
    main()
